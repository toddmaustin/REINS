"""Generate simulation-only injectors from the reviewed, stable RTL site catalog."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
# Keep catalog bytes/IDs stable so already saved public fault manifests still replay.
CATALOG_TARGETS = {"platform": "r05", "verifier": "r10c"}


def load_catalog(path):
    """Read path and reject duplicate IDs, unsupported targets and invalid widths."""
    data = json.loads(Path(path).read_text())
    assert data["format_version"] == 1 and data["payload_bits"] == 4096
    seen = set()
    for site in data["sites"]:
        assert 0 < site["id"] < 65536 and site["id"] not in seen
        assert site["target"] in ("r05", "r10c")
        assert 0 < sum(part["width"] for part in site["parts"]) <= 4096
        assert all(part["width"] > 0 for part in site["parts"])
        seen.add(site["id"])
    return data


def expression(site):
    """Return the packed concatenation of site's independently read target parts."""
    parts = [part["expression"] for part in site["parts"]]
    return parts[0] if len(parts) == 1 else "{" + ",".join(parts) + "}"


def generate(data, target):
    """Render target's readback, trigger, force/release and application-acknowledgement logic."""
    catalog_target = CATALOG_TARGETS.get(target, target)
    if catalog_target not in CATALOG_TARGETS.values():
        raise ValueError(f"unknown fault target: {target}")
    sites = [site for site in data["sites"] if site["target"] == catalog_target]
    out = ["// GENERATED by tools/generate_fault_sites.py; SIMULATION ONLY.",
           "`ifndef SYNTHESIS",
           "// Immediate assignment is intentional: read, modify and force before the DUT edge.",
           "/* verilator lint_off BLKSEQ */",
           "logic [4095:0] injected_value_q, before_value_q;",
           "logic [15:0] active_site_q; logic effect_q;",
           "function automatic logic [4095:0] read_fault_site(input logic [15:0] site);",
           "// Read site directly, independently of the selected force value.",
           "case(site)"]
    for site in sites:
        out.append(f"16'd{site['id']}: read_fault_site=4096'({expression(site)});")
    out += ["default: read_fault_site='0; endcase endfunction", "always_comb begin",
            "fault_width_o=0; fault_trigger_o=0; fault_unsupported_o=(fault_probe_i!=0);",
            "case(fault_probe_i)"]
    for site in sites:
        width = sum(part["width"] for part in site["parts"])
        out.append(f"16'd{site['id']}: begin fault_width_o=13'd{width}; fault_trigger_o=({site['trigger']}); fault_unsupported_o=0; end")
    out += ["default: begin end endcase end",
            "assign fault_active_o=active_site_q;",
            "assign fault_before_o=before_value_q;",
            "assign fault_observed_o=read_fault_site(active_site_q);",
            "assign fault_applied_o=active_site_q!=0 && fault_observed_o==injected_value_q;",
            "assign fault_effect_o=fault_applied_o && effect_q;",
            "assign fault_clean_o=active_site_q==0;",
            "// Arm may precede the trigger by many jobs. Apply before the next DUT edge.",
            "always @(negedge clk_i or fault_i or fault_mode_i or fault_value_i or fault_mask_i or fault_trigger_o) begin",
            "if (active_site_q!=0 && fault_i!=active_site_q) begin case(active_site_q)"]
    for site in sites:
        releases = " ".join(f"release {part['expression']};" for part in site["parts"])
        out.append(f"16'd{site['id']}: begin {releases} end")
    out += ["default: begin end endcase active_site_q=0; end",
            "if (active_site_q==0 && fault_i!=0 && fault_probe_i==fault_i && fault_trigger_o && !fault_unsupported_o) begin",
            "before_value_q=read_fault_site(fault_i); injected_value_q=before_value_q;",
            "case(fault_mode_i)",
            "3'd0: begin case(fault_i)"]
    for site in sites:
        default = site.get("legacy_value", "'0")
        out.append(f"16'd{site['id']}: injected_value_q=4096'({default});")
    out += ["default: injected_value_q=before_value_q; endcase end",
            "3'd1: injected_value_q=before_value_q ^ fault_mask_i; // transient bit flip",
            "3'd2: injected_value_q=(before_value_q & ~fault_mask_i) | (fault_value_i & fault_mask_i);",
            "3'd3: injected_value_q=before_value_q & ~fault_mask_i; // stuck low",
            "3'd4: injected_value_q=before_value_q | fault_mask_i; // stuck high",
            "default: injected_value_q=before_value_q; endcase",
            "// Mask unused payload bits so readback acknowledgement cannot ignore a truncation.",
            "injected_value_q=injected_value_q & ({4096{1'b1}} >> (4096-int'(fault_width_o)));",
            "effect_q=(before_value_q!=injected_value_q); active_site_q=fault_i;",
            "fault_activations_o=fault_activations_o+32'd1; case(fault_i)"]
    for site in sites:
        width = sum(part["width"] for part in site["parts"])
        assignments = []
        for part in site["parts"]:
            width -= part["width"]
            # A part-select avoids assigning a generic logic vector to a typed enum.
            lhs = part["expression"]
            if lhs.endswith("phase_q"):
                lhs += f"[{part['width']-1}:0]"
            assignments.append(f"force {lhs}=injected_value_q[{width} +: {part['width']}];")
        out.append(f"16'd{site['id']}: begin {' '.join(assignments)} end")
    out += ["default: begin end endcase end end", "initial begin active_site_q=0; injected_value_q=0; before_value_q=0; effect_q=0; fault_activations_o=0;"]
    for site in sites:
        for part in site["parts"]:
            out.append(f"assert ($bits({part['expression']})=={part['width']}) else $fatal(1,\"fault catalog width: {site['id']}\");")
    out += ["end", "/* verilator lint_on BLKSEQ */", "`endif", ""]
    return "\n".join(out)


def main():
    """Parse catalog/output paths and emit both injectors; no positional parameters."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--catalog", type=Path, default=ROOT / "tools/fault_sites.json")
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    data = load_catalog(args.catalog)
    args.output.mkdir(parents=True, exist_ok=True)
    for target in CATALOG_TARGETS:
        (args.output / f"{target}_fault_sites.svh").write_text(generate(data, target))


if __name__ == "__main__":
    main()
